-- Инструмент manage_memory_conflict удалён вместе с механизмом споров между версиями записей
-- (#340): споры не создаются с v0.12.0, а разрешать их было нечем. Выдача внешней группы с
-- неизвестным именем делает недействительной всю её политику, поэтому имя убирается из каждой
-- сохранённой выдачи; остальные выданные инструменты остаются как были. Таблица claim_conflicts
-- остаётся историей: она пуста, и её никто больше не пишет и не читает.
UPDATE telegram_groups
   SET tool_allowlist = array_remove(tool_allowlist, 'manage_memory_conflict')
 WHERE tool_allowlist @> ARRAY['manage_memory_conflict']::text[];
