-- Память не отличает запись, которая пригождается в каждом втором разговоре, от записи, которую
-- ни разу не использовали с момента сохранения. Обе стоят в очереди на выдачу на равных.
--
-- Поля для учёта есть, но считают они другое: `reinforcement_count` растёт, когда факт наблюдают
-- заново, то есть когда в память пишут ровно тот же текст. На боевой базе он равен нулю у 1456
-- записей из 1465 и ни разу не дошёл до двух. «Факт наблюдали заново» и «запись пригодилась в
-- ответе» — разные вещи, и смешав их в одном поле, мы потеряли бы оба смысла.
ALTER TABLE memory_items_all
  ADD COLUMN usage_count integer NOT NULL DEFAULT 0 CHECK (usage_count >= 0),
  ADD COLUMN last_used_at timestamptz;

-- Кривая забывания спрашивает «сколько раз этой записью пользовались» на каждом ранжировании.
CREATE INDEX memory_items_all_usage ON memory_items_all (usage_count DESC, last_used_at DESC);

-- `memory_items` — представление с `SELECT *`, развёрнутым в список колонок в момент создания.
-- Новые колонки базовой таблицы сами в нём не появятся, поэтому представление пересоздаётся.
-- Замена допустима: новые колонки добавляются в конец, порядок и типы прежних не меняются.
CREATE OR REPLACE VIEW memory_items AS
  SELECT * FROM memory_items_all WHERE deleted_at IS NULL;
