-- «Пётр» и «Петр» для точной ветки поиска — разные слова, и это бьёт ровно по тому, ради чего
-- ветка существует: по именам, фамилиям и названиям. В русском тексте «ё» пишут непоследовательно,
-- и запись могла попасть в память из голосовой расшифровки с «ё», а человек набирает руками «е».
-- На боевой базе «ё» содержат 507 активных записей из 1465.
--
-- Словарь `simple` намеренно ничего не делает со словом, кроме нижнего регистра — в этом его смысл,
-- он ловит точные токены. Поэтому сведение «ё» к «е» делается до него, прямо в выражении колонки.
-- Морфологическую ветку это не касается: там стеммер сводит «ё» сам, и вмешиваться туда не нужно.
--
-- `SET EXPRESSION` (PostgreSQL 17) переписывает таблицу и перестраивает индексы, не трогая саму
-- колонку, поэтому представление `memory_items` и вьюхи наблюдения над ним остаются на месте.
-- `unaccent` не используется намеренно: оно трогает всю диакритику, а нужна одна буква.
ALTER TABLE memory_items_all
  ALTER COLUMN search_vector
  SET EXPRESSION AS (to_tsvector('simple', translate(content, 'ёЁ', 'еЕ')));
