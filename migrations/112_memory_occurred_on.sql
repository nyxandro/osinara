-- «Что мы решали в августе?» память отвечает случайно: она находит записи, где слово «август»
-- встречается в тексте, но не те, которые к августу относятся. Единственный признак времени у
-- записи — когда её сохранили, а это другой вопрос. Разговор о прошлогодней поездке, состоявшийся
-- сегодня, создаёт запись с сегодняшней датой, и 58% памяти создано за три активных дня: как ось
-- времени дата создания заведомо непригодна.
--
-- Дата события необязательна и никогда не выдумывается: не известна из разговора — пустая, и
-- запись ведёт себя ровно как прежде. У 196 существующих эпизодов её не будет никогда, и это
-- принимается как данность, а не заполняется задним числом.
--
-- Хранится датой, а не отметкой времени: разговор даёт день, а не час, и часовой пояс здесь
-- создал бы сдвиг на сутки вместо точности, которой в источнике нет.
ALTER TABLE memory_items_all
  ADD COLUMN occurred_on date,
  -- Границы ловят не ошибку модели в дне, а бессмыслицу: год 20260 или событие при Иване Грозном.
  ADD CONSTRAINT memory_items_occurred_on_range CHECK (
    occurred_on IS NULL OR occurred_on BETWEEN DATE '1900-01-01' AND DATE '2100-01-01'
  );

-- Окно «с» и «по» перебирает записи одной области памяти по дате события.
CREATE INDEX memory_items_all_occurred_on
  ON memory_items_all (family_id, scope, scope_partition_key, occurred_on)
  WHERE occurred_on IS NOT NULL AND claim_status = 'active' AND deleted_at IS NULL;

-- `memory_items` — представление с `SELECT *`, развёрнутым в список колонок в момент создания.
CREATE OR REPLACE VIEW memory_items AS
  SELECT * FROM memory_items_all WHERE deleted_at IS NULL;
