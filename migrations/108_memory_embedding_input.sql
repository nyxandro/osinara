-- В смысловой вектор уходил голый текст записи, без указания, о ком она. Отсюда подмена сущностей:
-- на вопрос про репозиторий Осинары находится репозиторий чужого проекта, на вопрос про ассистента
-- Иву — документация Eve. Модель на 384 измерения различает редкие имена собственные слабо, и в
-- похожем контексте («репозиторий», «проект», «ссылка») они для неё почти одно и то же.
--
-- Решение — класть в вектор текст с шапкой: субъект записи и её вид. Но инвариант «кусок есть
-- точный срез оригинала» ломать нельзя: он защищает от рассинхрона индекса и текста, и проверяется
-- при каждой записи в индекс. Поэтому текст, реально ушедший в модель, живёт в отдельной колонке,
-- а `content` остаётся срезом.
--
-- Существующие строки заполняются собственным `content`: они и были проиндексированы без шапки, и
-- колонка должна говорить правду о том, что ушло в модель. Переиндексация — отдельный шаг выпуска,
-- а не часть миграции: пока запись не переиндексирована, смысловая ветка её не видит, и окно этого
-- простоя выбирает тот, кто выпускает релиз.
ALTER TABLE memory_embedding_chunks ADD COLUMN embedding_input text;

UPDATE memory_embedding_chunks SET embedding_input = content WHERE embedding_input IS NULL;

ALTER TABLE memory_embedding_chunks
  ALTER COLUMN embedding_input SET NOT NULL,
  ADD CONSTRAINT memory_embedding_chunks_input_not_empty
    CHECK (char_length(embedding_input) > 0);
