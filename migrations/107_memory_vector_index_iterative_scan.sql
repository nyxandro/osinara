-- Векторный индекс HNSW построен с самого начала, но им не пользовался ни один запрос: pgvector
-- применяет его только к форме «сортируй по расстоянию, возьми N», а смысловая ветка считала
-- расстояние под MIN() с группировкой по записи. Форма запроса исправлена отдельно; здесь —
-- настройка, без которой пользоваться индексом было бы опасно.
--
-- Приблизительный обход по своей природе отдаёт фиксированную порцию ближайших кусков и только
-- потом к ним применяется предикат доступа: чужие куски отсеиваются, и у семьи, владеющей малой
-- долей записей, выдача схлопывается почти до пустой. Это известная ловушка фильтрованного
-- векторного поиска, и pgvector 0.8 закрывает её итеративным обходом: индекс продолжает отдавать
-- кандидатов, пока не наберётся нужное число прошедших фильтр.
--
-- `relaxed_order` выбран вместо `strict_order` потому, что точный порядок расстояний здесь не
-- нужен: отобранные куски всё равно сводятся к записям через MIN() и заново сортируются, а затем
-- объединяются с другими ветками по местам, а не по расстояниям. `strict_order` стоил бы
-- дополнительной сортировки ради порядка, который тут же теряется.
--
-- Настройка на уровне базы, а не на уровне запроса: `SET LOCAL` потребовал бы обернуть каждый
-- поиск в транзакцию ради одного параметра, а `SET` на соединении из пула протёк бы в соседние
-- запросы незаметно. Оператор `<=>` используется не только поиском памяти — ещё сверкой названий
-- и назначений нитей, — но HNSW-индекс построен только на кусках памяти, а без индекса настройка
-- не делает ничего. Область действия поэтому шире назначения ровно настолько, насколько это
-- безразлично.
--
-- Имя базы подставляется из `current_database()`: в разработке, в тестах и на бою оно разное.
DO $$
BEGIN
  EXECUTE format(
    'ALTER DATABASE %I SET hnsw.iterative_scan = %L', current_database(), 'relaxed_order'
  );
END $$;
