-- Маркер «промолчать» в сохранённой истории разговоров получает текущее написание. Модель видит
-- свои прошлые ответы и повторяет маркер из них; ядро распознаёт только `<empty-delivery/>`, и
-- старое написание дошло бы до человека обычным текстом. Маркер не содержит символов, которые JSON
-- экранирует, поэтому замена по тексту сообщения оставляет его корректным JSON.
UPDATE agent_session_history
   SET message = replace(message::text, '<eve-empty-delivery/>', '<empty-delivery/>')::json
 WHERE message::text LIKE '%<eve-empty-delivery/>%';
