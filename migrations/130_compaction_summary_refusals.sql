-- Отказы модели пересказать старую часть истории подряд, с последнего удачного сжатия (#331).
-- Без счётчика следующее сообщение посылало тот же запрос на пересказ той же истории и получало
-- тот же отказ — чат замолкал навсегда. Каждый отказ вдвое уменьшает следующий запрос, после
-- четырёх старая часть выпадает с пометкой. Удачное сжатие обнуляет счётчик.
ALTER TABLE agent_session_state
  ADD COLUMN compaction_summary_refusals smallint NOT NULL DEFAULT 0
    CHECK (compaction_summary_refusals >= 0);
