-- Воркер индексации памяти может зависнуть, оставаясь живым процессом, и этого не заметит никто.
-- Воспоминания продолжают ложиться в базу, но перестают находиться смысловым поиском; снаружи это
-- неотличимо от обычного промаха. Из трёх обычных сигналов не работал ни один: healthcheck не
-- заведён, логов нет по построению («молчание = ошибок не было»), а метрика по очереди задач
-- считает только то, что в таблице есть — выполненные задачи из неё уходят, поэтому при пустой
-- очереди исправная работа и остановка дают одно и то же число.
--
-- Нужна величина, которая при работе отличается от значения при остановке. Возраст самой старой
-- ожидающей задачи — ровно такая: у живого воркера он держится около нуля, у вставшего растёт
-- линейно. Это повторяет уже принятую в проекте форму `osinara_ingress_oldest_pending_age_seconds`.
--
-- Оговорка честная: при пустой очереди сигнала нет и здесь. Этот случай ловит с другой стороны
-- `monitoring_memory_index_state` — стоячее состояние самих записей, которое не гаснет само.
CREATE VIEW monitoring_memory_embedding_backlog AS
  SELECT count(*) AS pending,
         COALESCE(EXTRACT(EPOCH FROM (now() - min(created_at)))::bigint, 0)
           AS oldest_pending_age_seconds
  FROM memory_embedding_jobs
  WHERE status IN ('pending', 'leased');

GRANT SELECT ON monitoring_memory_embedding_backlog TO osinara_metrics;
